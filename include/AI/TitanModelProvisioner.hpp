    inline std::filesystem::path EnsureLocalModelsProvisioned() noexcept {
        try {
            wchar_t exePath[MAX_PATH]{};
            std::filesystem::path baseDir = std::filesystem::current_path();
            if (::GetModuleFileNameW(nullptr, exePath, MAX_PATH) > 0) {
                baseDir = std::filesystem::path(exePath).parent_path();
            }
            std::filesystem::path modelsDir = baseDir / L"assets" / L"models";
            std::error_code ec;
            std::filesystem::create_directories(modelsDir, ec);

            auto unpackFile = [&](const wchar_t* fileName, const uint8_t* dataPtr, size_t dataSize) {
                std::filesystem::path filePath = modelsDir / fileName;
                if (!std::filesystem::exists(filePath, ec) || std::filesystem::file_size(filePath, ec) < dataSize) {
                    std::ofstream out(filePath, std::ios::binary | std::ios::trunc);
                    if (out.is_open()) {
                        out.write(reinterpret_cast<const char*>(dataPtr), static_cast<std::streamsize>(dataSize));
                        out.flush();
                    }
                }
            };

            unpackFile(L"ember_pe.onnx", kEmbeddedEmberOnnx.data(), kEmbeddedEmberOnnx.size());
            unpackFile(L"cic_ids2018.onnx", kEmbeddedCicIdsOnnx.data(), kEmbeddedCicIdsOnnx.size());
            unpackFile(L"titan_brain_memory.bin", kEmbeddedBrainMemory.data(), kEmbeddedBrainMemory.size());
            return modelsDir;
        } catch (...) {
            return std::filesystem::path(L"assets\\models");
        }
    }

